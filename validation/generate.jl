function normalize_export(token)
    token = strip(token)
    isempty(token) && return nothing
    return token
end

"""
Return the supported exported API inventory for a package.

Most packages use explicit `export` statements in their main module. Packages
whose exports are generated by metaprogramming may provide a reviewed
`validation/exports-<package>.txt` inventory so linting stays deterministic and
does not initialize optional runtimes merely to inspect a module.
"""
function exported_symbols(pkg)
    inventory_path = joinpath(@__DIR__, "exports-$(pkg).txt")
    if isfile(inventory_path)
        inventory = String[]
        for raw_line in eachline(inventory_path)
            token = strip(first(split(raw_line, '#'; limit=2)))
            isempty(token) || push!(inventory, token)
        end
        isempty(inventory) && error("$pkg exported API inventory is empty")
        length(inventory) == length(unique(inventory)) ||
            error("$pkg exported API inventory contains duplicates")
        return inventory
    end

    path = joinpath(ROOT, pkg, "src", "$(pkg).jl")
    exports = String[]
    continuing = false
    for raw_line in eachline(path)
        code = strip(first(split(raw_line, '#'; limit=2)))
        if startswith(code, "export ")
            payload = strip(code[8:end])
            continuing = endswith(payload, ',')
        elseif continuing
            isempty(code) && continue
            payload = code
            continuing = endswith(payload, ',')
        else
            continue
        end
        for token in split(payload, ',')
            normalized = normalize_export(token)
            normalized === nothing || push!(exports, normalized)
        end
    end
    return unique(exports)
end

function safe_package_path(pkg, relative_path, kind)
    relative_path isa AbstractString || error("$pkg $kind path is not a string")
    isabspath(relative_path) && error("$pkg $kind path must be package-relative: $relative_path")
    normalized = normpath(relative_path)
    (normalized == ".." || startswith(normalized, ".." * Base.Filesystem.path_separator)) &&
        error("$pkg $kind path escapes the package: $relative_path")
    candidate = joinpath(ROOT, pkg, normalized)
    isfile(candidate) || error("$pkg $kind path does not exist: $relative_path")
    return normalized
end

function read_matrix(pkg)
    path = matrix_path(pkg)
    isfile(path) || error("missing traceability matrix: $(relpath(path, ROOT))")
    rows = YAML.load_file(path)
    rows isa AbstractVector || error("$pkg matrix must contain a YAML list")
    isempty(rows) && error("$pkg matrix is empty")
    return rows
end

function git_blob_bytes(commit, repository_path; root=ROOT)
    spec = "$(commit):$(replace(repository_path, '\\' => '/'))"
    return read(Cmd(["git", "-C", root, "show", spec]))
end

function validate_package_matrix_copy(path, pkg; release=true, commit=nothing, root=ROOT)
    expected = if release
        commit === nothing && error("release matrix validation requires a commit")
        git_blob_bytes(commit, "validation/matrix-$pkg.yaml"; root)
    else
        read(matrix_path(pkg))
    end
    read(path) == expected || error(
        "$pkg copied matrix does not exactly match " *
        (release ? "the matrix at $commit" : "the current package matrix"))
    return true
end

"""Return literal `include("...")` arguments from executable Julia syntax."""
function literal_includes(source::AbstractString; filename="none")
    syntax = Meta.parseall(source; filename)
    includes = String[]

    function visit(node)
        node isa Expr || return
        node.head in (:quote, :inert) && return
        if node.head == :call && length(node.args) == 2 &&
           node.args[1] === :include && node.args[2] isa String
            push!(includes, node.args[2])
        end
        foreach(visit, node.args)
    end

    visit(syntax)
    return includes
end

"""Return the package-relative files reached by literal `include("...")` calls."""
function executed_test_files(pkg)
    test_root = joinpath(ROOT, pkg, "test")
    entrypoint = joinpath(test_root, "runtests.jl")
    isfile(entrypoint) || error("$pkg has no canonical test/runtests.jl")
    visited = Set{String}()

    function visit(path)
        absolute = normpath(path)
        relative = relpath(absolute, joinpath(ROOT, pkg))
        relative in visited && return
        isfile(absolute) || error("$pkg test suite includes a missing file: $relative")
        push!(visited, relative)
        source = read(absolute, String)
        for included in literal_includes(source; filename=absolute)
            visit(joinpath(dirname(absolute), included))
        end
    end

    visit(entrypoint)
    return visited
end

"""Validate matrix schema, file paths, uniqueness, and complete exported API coverage."""
function validate_matrix(pkg)
    rows = read_matrix(pkg)
    executed_tests = executed_test_files(pkg)
    entrypoints = String[]
    for (index, row) in pairs(rows)
        row isa AbstractDict || error("$pkg matrix row $index is not a mapping")
        for key in ("entrypoint", "code", "doc", "tests")
            haskey(row, key) || error("$pkg matrix row $index is missing `$key`")
        end
        entrypoint = string(row["entrypoint"])
        isempty(strip(entrypoint)) && error("$pkg matrix row $index has an empty entrypoint")
        push!(entrypoints, entrypoint)

        code = safe_package_path(pkg, row["code"], "code")
        startswith(code, "src" * Base.Filesystem.path_separator) ||
            error("$pkg code evidence must be under src/: $code")
        occursin(entrypoint, read(joinpath(ROOT, pkg, code), String)) ||
            error("$pkg code evidence does not name `$entrypoint`: $code")

        doc = safe_package_path(pkg, row["doc"], "documentation")
        (startswith(doc, "docs" * Base.Filesystem.path_separator) || doc == "README.md") ||
            error("$pkg documentation evidence must be README.md or under docs/: $doc")
        occursin(entrypoint, read(joinpath(ROOT, pkg, doc), String)) ||
            error("$pkg documentation evidence does not name `$entrypoint`: $doc")

        tests = row["tests"]
        tests isa AbstractVector || error("$pkg matrix row $index `tests` must be a list")
        isempty(tests) && error("$pkg matrix row $index has no test evidence")
        for test_path in tests
            test = safe_package_path(pkg, test_path, "test")
            startswith(test, "test" * Base.Filesystem.path_separator) ||
                error("$pkg test evidence must be under test/: $test")
            test in executed_tests ||
                error("$pkg test evidence is not reached from test/runtests.jl: $test")
        end
    end

    length(entrypoints) == length(unique(entrypoints)) ||
        error("$pkg matrix contains duplicate entrypoints")
    expected = Set(exported_symbols(pkg))
    actual = Set(entrypoints)
    missing = sort!(collect(setdiff(expected, actual)))
    extra = sort!(collect(setdiff(actual, expected)))
    isempty(missing) || error("$pkg matrix is missing exported APIs: $(join(missing, ", "))")
    isempty(extra) || error("$pkg matrix contains non-exported APIs: $(join(extra, ", "))")
    return rows
end

function validate_all_matrices()
    for pkg in PACKAGES
        rows = validate_matrix(pkg)
        println("validated $pkg matrix: $(length(rows)) exported entrypoints")
    end
    return true
end

function clean_coverage(pkg; root=ROOT)
    package_root = joinpath(root, pkg)
    isdir(package_root) || return
    for (dir, _, files) in walkdir(package_root)
        for file in files
            endswith(file, ".cov") && rm(joinpath(dir, file); force=true)
        end
    end
end

generated_environment_filename(name) =
    name in ("Manifest.toml", "LocalPreferences.toml", "JuliaLocalPreferences.toml") ||
    occursin(r"^Manifest-v\d+\.\d+\.toml$", name)

function remove_generated_path(path)
    (ispath(path) || islink(path)) || return 0
    if islink(path)
        rm(path; force=true)
    else
        rm(path; force=true, recursive=isdir(path))
    end
    return 1
end

function clean_environment_artifacts(; root=ROOT, packages=PACKAGES)
    environment_dirs = [root, joinpath(root, "validation")]
    for pkg in packages
        package_root = joinpath(root, pkg)
        append!(environment_dirs, [
            package_root,
            joinpath(package_root, "test"),
            joinpath(package_root, "docs"),
        ])
    end

    removed = 0
    for directory in unique(environment_dirs)
        isdir(directory) || continue
        for name in readdir(directory)
            generated_environment_filename(name) || continue
            removed += remove_generated_path(joinpath(directory, name))
        end
        removed += remove_generated_path(joinpath(directory, ".CondaPkg"))
        removed += remove_generated_path(joinpath(directory, "Rplots.pdf"))
    end
    for pkg in packages
        docs = joinpath(root, pkg, "docs")
        removed += remove_generated_path(joinpath(docs, "build"))
        removed += remove_generated_path(joinpath(docs, "site"))
    end
    return removed
end

function sanitize_transcript(text::AbstractString;
                             root::AbstractString=ROOT,
                             home::AbstractString=homedir(),
                             bug_reports_url::AbstractString=strip(get(ENV, "QSPKIT_BUG_REPORTS_URL", "")))
    sanitized = String(text)
    replacements = Pair{String, String}[]
    function add_replacements(private_value, label)
        isempty(private_value) && return
        value = String(private_value)
        for variant in unique([value, replace(value, '\\' => "\\\\"),
                               replace(value, '/' => "\\/")])
            push!(replacements, variant => label)
        end
    end
    add_replacements(root, "<QSPKIT_ROOT>")
    home == "/" || add_replacements(home, "<HOME>")
    add_replacements(bug_reports_url, "<BUG_REPORTS_URL>")
    sort!(replacements; by=pair -> -length(first(pair)))
    for (private_value, label) in replacements
        sanitized = replace(sanitized, private_value => label)
    end
    for regex in SANITIZATION_HOME_REGEXES
        sanitized = replace(sanitized, regex => "<PRIVATE_PATH>")
    end
    return sanitized
end

function validate_public_text_payload(text::AbstractString, label)
    sanitize_transcript(text) == text ||
        error("$label contains an unsanitized local path or endpoint")
    findings = scan_text(text, label)
    isempty(findings) || throw(sanitization_error("$label privacy scan", findings))
    return true
end

function publish_sanitized_transcript!(raw_path, destination)
    sanitized = sanitize_transcript(read(raw_path, String))
    validate_public_text_payload(sanitized, basename(destination))
    mkpath(dirname(destination))
    temporary, io = mktemp(dirname(destination))
    try
        write(io, sanitized)
        close(io)
        mv(temporary, destination; force=true)
    catch
        isopen(io) && close(io)
        ispath(temporary) && rm(temporary; force=true)
        rethrow()
    end
    return destination
end

function capture_sanitized_transcripts(runner, stdout_path, stderr_path)
    return mktempdir() do capture_dir
        raw_stdout = joinpath(capture_dir, "stdout")
        raw_stderr = joinpath(capture_dir, "stderr")
        result = open(raw_stdout, "w") do stdout_io
            open(raw_stderr, "w") do stderr_io
                runner(stdout_io, stderr_io)
            end
        end
        publish_sanitized_transcript!(raw_stdout, stdout_path)
        publish_sanitized_transcript!(raw_stderr, stderr_path)
        return result
    end
end

process_status(exit_code::Integer) = exit_code == 0 ? "PASS" : "FAIL"
process_score(exit_code::Integer) = exit_code == 0 ? 1.0 : 0.0

function process_command(pkg, kind::Symbol)
    if kind == :tests
        return "julia --startup-file=no --project=$pkg/test --code-coverage=user -e include(\"$pkg/test/runtests.jl\")"
    elseif kind == :docs
        return "julia --startup-file=no --project=$pkg/docs -e include(\"$pkg/docs/make.jl\")"
    end
    error("unsupported package process kind: $kind")
end

function canonical_process_check(pkg, kind::Symbol, exit_code::Integer,
                                 stdout_name::AbstractString,
                                 stderr_name::AbstractString,
                                 stdout_text::AbstractString,
                                 stderr_text::AbstractString)
    label = kind == :tests ? "tests" :
        kind == :docs ? "docs" : error("unsupported package process kind: $kind")
    io = IOBuffer()
    println(io, process_status(exit_code))
    println(io, "package: $pkg")
    println(io, "process: $label")
    println(io, "command: $(process_command(pkg, kind))")
    println(io, "exit_code: $exit_code")
    println(io, "stdout: $stdout_name")
    println(io, "stderr: $stderr_name")
    for (stream_label, contents) in
        (("captured stdout", stdout_text), ("captured stderr", stderr_text))
        println(io)
        println(io, "=== $stream_label ===")
        write(io, contents)
        isempty(contents) || endswith(contents, "\n") || println(io)
    end
    return String(take!(io))
end

function write_process_check(path, pkg, kind::Symbol, exit_code::Integer,
                             stdout_path, stderr_path)
    contents = canonical_process_check(
        pkg,
        kind,
        exit_code,
        basename(stdout_path),
        basename(stderr_path),
        read(stdout_path, String),
        read(stderr_path, String),
    )
    open(path, "w") do io
        write(io, contents)
    end
    return path
end

function validate_process_evidence(pkg, prefix, kind::Symbol, exit_code::Integer)
    suffix = kind == :tests ? "tests" :
        kind == :docs ? "docs" : error("unsupported package process kind: $kind")
    check_path = kind == :tests ? prefix * ".check.txt" : prefix * ".docs.check.txt"
    stdout_path = prefix * ".$suffix.stdout"
    stderr_path = prefix * ".$suffix.stderr"
    expected = canonical_process_check(
        pkg,
        kind,
        exit_code,
        basename(stdout_path),
        basename(stderr_path),
        read(stdout_path, String),
        read(stderr_path, String),
    )
    read(check_path, String) == expected ||
        error("$pkg $suffix check is not the canonical process record")
    return true
end

function validate_process_score_bindings(pkg, scores, test_exit_code::Integer,
                                         docs_exit_code::Integer)
    scores["testing"]["check"] == process_score(test_exit_code) ||
        error("$pkg testing.check does not match the recorded test exit code")
    scores["documentation"]["has_website"] == process_score(docs_exit_code) ||
        error("$pkg documentation score does not match the recorded docs exit code")
    return true
end

function run_package_tests(pkg, prefix)
    clean_coverage(pkg)
    stdout_path = prefix * ".tests.stdout"
    stderr_path = prefix * ".tests.stderr"
    test_file = joinpath(ROOT, pkg, "test", "runtests.jl")
    expression = "include($(repr(test_file)))"
    command = `$(Base.julia_cmd()) --startup-file=no --project=$(joinpath(ROOT, pkg, "test")) --code-coverage=user -e $expression`
    exit_code = capture_sanitized_transcripts(stdout_path, stderr_path) do stdout_io, stderr_io
        process = cd(ROOT) do
            run(pipeline(ignorestatus(command); stdout=stdout_io, stderr=stderr_io))
        end
        process.exitcode
    end
    write_process_check(
        prefix * ".check.txt", pkg, :tests, exit_code, stdout_path, stderr_path)
    return exit_code == 0, exit_code
end

function run_package_docs(pkg, prefix)
    stdout_path = prefix * ".docs.stdout"
    stderr_path = prefix * ".docs.stderr"
    check_path = prefix * ".docs.check.txt"
    docs_project = joinpath(ROOT, pkg, "docs")
    docs_file = joinpath(docs_project, "make.jl")
    build_dir = joinpath(docs_project, "build")
    isdir(build_dir) && rm(build_dir; recursive=true)

    exit_code = capture_sanitized_transcripts(stdout_path, stderr_path) do stdout_io, stderr_io
        if isfile(joinpath(docs_project, "Project.toml")) && isfile(docs_file)
            expression = "include($(repr(docs_file)))"
            command = `$(Base.julia_cmd()) --startup-file=no --project=$docs_project -e $expression`
            process = cd(ROOT) do
                run(pipeline(ignorestatus(command); stdout=stdout_io, stderr=stderr_io))
            end
            process.exitcode
        else
            println(stderr_io, "missing $pkg/docs/Project.toml or $pkg/docs/make.jl")
            1
        end
    end

    write_process_check(
        check_path, pkg, :docs, exit_code, stdout_path, stderr_path)
    return exit_code == 0, exit_code
end

function collect_coverage(pkg)
    source = joinpath(ROOT, pkg, "src")
    coverage = Coverage.process_folder(source)
    files = Any[]
    covered_lines = 0
    executable_lines = 0
    for file_coverage in coverage
        covered, executable = Coverage.get_summary(file_coverage)
        covered_lines += covered
        executable_lines += executable
        executable == 0 && continue
        push!(files, Dict(
            "file" => relpath(file_coverage.filename, joinpath(ROOT, pkg)),
            "coverage" => 100 * covered / executable,
        ))
    end
    sort!(files; by=item -> item["file"])
    overall = executable_lines == 0 ? 0.0 : 100 * covered_lines / executable_lines
    return Dict(
        "overall" => overall,
        "files" => files,
    ), Dict(
        "covered_lines" => covered_lines,
        "executable_lines" => executable_lines,
        "formula" => "100 * covered_lines / executable_lines",
    )
end

changelog_line_current(text, pkg, version) =
    any(line -> occursin(pkg, line) && occursin(version, line), eachline(IOBuffer(text)))

function changelog_status(pkg, version)
    path = joinpath(ROOT, "CHANGELOG.md")
    isfile(path) || return 0.0, 0.0
    text = read(path, String)
    current = changelog_line_current(text, pkg, version)
    return 1.0, current ? 1.0 : 0.0
end

function package_non_test_scores(pkg, docs_passed)
    project = package_project(pkg)
    has_news, news_current = changelog_status(pkg, string(project["version"]))
    authors = get(project, "authors", Any[])
    has_maintainer = authors isa AbstractVector && !isempty(authors)
    alpha_commit, _ = alpha_git_state()
    has_source_control = alpha_commit !== nothing
    bug_reports_url = strip(get(ENV, "QSPKIT_BUG_REPORTS_URL", ""))
    return Dict(
        "documentation" => Dict(
            "has_website" => docs_passed ? 1.0 : 0.0,
            "has_news" => has_news,
        ),
        "maintenance" => Dict(
            "has_maintainer" => has_maintainer ? 1.0 : 0.0,
            "news_current" => news_current,
        ),
        "transparency" => Dict(
            "has_source_control" => has_source_control ? 1.0 : 0.0,
            "has_bug_reports_url" => isempty(bug_reports_url) ? 0.0 : 1.0,
        ),
    )
end

function package_scores(pkg, passed, docs_passed, coverage_percent)
    result = package_non_test_scores(pkg, docs_passed)
    result["testing"] = Dict(
        "check" => passed ? 1.0 : 0.0,
        "coverage" => coverage_percent / 100,
    )
    return result
end

function alpha_git_state()
    isdir(joinpath(ROOT, ".git")) || return nothing, false
    try
        commit = strip(read(`git -C $ROOT rev-parse HEAD`, String))
        clean = isempty(strip(read(`git -C $ROOT status --porcelain`, String)))
        return commit, clean
    catch
        return nothing, false
    end
end

function release_commit(state=alpha_git_state())
    commit, clean = state
    commit === nothing && error("release evidence requires a Git repository with at least one commit")
    clean || error("release evidence requires a clean Git working tree")
    occursin(r"^[0-9a-f]{40}([0-9a-f]{24})?$", commit) ||
        error("release evidence requires a full Git commit object ID")
    return commit
end

function validate_release_source_info(source, expected_commit; require_workspace_archive=false)
    source["alpha_commit"] == expected_commit ||
        error("evidence alpha commit does not match current HEAD")
    source["alpha_worktree_clean"] === true ||
        error("evidence was not generated from a clean working tree")
    expected_mode = "git-archive:$expected_commit"
    source["archive_mode"] == expected_mode ||
        error("evidence source archive does not match current HEAD")
    if require_workspace_archive
        source["workspace_archive_mode"] == expected_mode ||
            error("evidence workspace archive does not match current HEAD")
    end
    return true
end

