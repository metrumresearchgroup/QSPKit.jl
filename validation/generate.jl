function working_tree_archive(path, entries)
    arguments = String["tar", "-czf", path]
    append!(arguments, ["--exclude=$pattern" for pattern in WORKING_TREE_ARCHIVE_EXCLUDES])
    append!(arguments, ["-C", ROOT])
    append!(arguments, entries)
    run(Cmd(arguments))
end

function git_archive_command(commit; package=nothing, root=ROOT)
    arguments = String[
        "git", "-C", root, "-c", "tar.umask=0002", "archive", "--format=tar", commit,
    ]
    if package !== nothing
        append!(arguments, ["--", string(package)])
    end
    return Cmd(arguments)
end

function write_git_archive(path, commit; package=nothing, root=ROOT)
    mkpath(dirname(path))
    temporary, io = mktemp(dirname(path))
    try
        compression = pipeline(
            git_archive_command(commit; package, root),
            `gzip -n -9 -c`,
        )
        run(pipeline(compression; stdout=io))
        close(io)
        mv(temporary, path; force=true)
    catch
        isopen(io) && close(io)
        ispath(temporary) && rm(temporary; force=true)
        rethrow()
    end
    return path
end

function expected_git_archive_digest(commit; package=nothing, root=ROOT,
                                     cache=EXPECTED_ARCHIVE_DIGEST_CACHE)
    package_key = package === nothing ? "" : string(package)
    key = (realpath(root), string(commit), package_key)
    return get!(cache, key) do
        bytes2hex(sha256(read(git_archive_command(commit; package, root))))
    end
end

function decompressed_archive_digest(path)
    isfile(path) || error("source archive does not exist: $path")
    return bytes2hex(sha256(read(`gzip -dc $path`)))
end

function validate_git_archive(path, commit; package=nothing, root=ROOT,
                              cache=EXPECTED_ARCHIVE_DIGEST_CACHE)
    actual = decompressed_archive_digest(path)
    expected = expected_git_archive_digest(commit; package, root, cache)
    actual == expected || error(
        "source archive is not the canonical git archive for " *
        (package === nothing ? "the workspace" : string(package)) * " at $commit")
    return true
end

function write_source_archive(path; package=nothing, release=true)
    commit, clean = alpha_git_state()
    release && (commit = release_commit((commit, clean)); clean = true)
    if commit !== nothing && clean
        write_git_archive(path, commit; package)
        return "git-archive:$commit"
    end

    entries = if package === nothing
        candidates = [
            ".github", ".gitignore", "BACKPORTS.md", "CHANGELOG.md", "CONTRIBUTING.md",
            "CondaPkg.toml", "PROVENANCE.md", "README.md", "SANITIZATION.md",
            "SECURITY.md", "Project.toml",
            PACKAGES..., "validation",
        ]
        filter(entry -> ispath(joinpath(ROOT, entry)), candidates)
    else
        [package]
    end
    working_tree_archive(path, entries)
    return "working-tree"
end

function copy_resolved_manifest(source, destination)
    isfile(source) || error("resolved dependency manifest is missing: $(relpath(source, ROOT))")
    manifest = TOML.parsefile(source)
    get(manifest, "manifest_format", nothing) == "2.0" ||
        error("unsupported dependency manifest format in $(relpath(source, ROOT))")
    relative = relpath(source, ROOT)
    tracked = !isempty(read(Cmd(["git", "-C", ROOT, "ls-files", "--cached", "--", relative])))
    tracked && error("resolved dependency manifest must remain untracked: $relative")
    success(Cmd(["git", "-C", ROOT, "check-ignore", "-q", "--", relative])) ||
        error("resolved dependency manifest is not covered by the ignore policy: $relative")
    cp(source, destination; force=true)
    return destination
end

file_sha256(path) = open(path, "r") do io
    bytes2hex(sha256(io))
end

function current_project_resolve_hash(project_path)
    isfile(project_path) || error("manifest-binding Project.toml is missing: $project_path")
    project_file = abspath(project_path)
    project = Pkg.Types.read_project(project_file)
    workspace = if isempty(project.workspace)
        Dict{String, Pkg.Types.Project}()
    else
        collected = Pkg.Types.collect_workspace(project_file)
        delete!(collected, project_file)
        collected
    end
    manifest = Pkg.Types.Manifest()
    manifest_file = joinpath(dirname(project_file), "Manifest.toml")
    env = Pkg.Types.EnvCache(
        project_file,
        project_file,
        manifest_file,
        nothing,
        project,
        workspace,
        manifest,
        deepcopy(project),
        deepcopy(manifest),
    )
    return Pkg.Types.workspace_resolve_hash(env)
end

function resolved_manifest_binding(artifact_path, project_relative_path)
    manifest = TOML.parsefile(artifact_path)
    project_hash = get(manifest, "project_hash", nothing)
    project_hash isa AbstractString && occursin(r"^[0-9a-f]{40}$", project_hash) ||
        error("resolved manifest does not contain a valid project_hash")
    expected_hash = current_project_resolve_hash(joinpath(ROOT, project_relative_path))
    project_hash == expected_hash || error(
        "resolved manifest project_hash does not match the current $project_relative_path")
    return Dict(
        "artifact" => basename(artifact_path),
        "sha256" => file_sha256(artifact_path),
        "project_hash" => project_hash,
        "project_file" => replace(project_relative_path, '\\' => '/'),
        "policy" => MANIFEST_BINDING_POLICY,
    )
end

function validate_resolved_manifest_binding(binding, artifact_path,
                                            project_relative_path)
    require_exact_keys(
        binding,
        ["artifact", "sha256", "project_hash", "project_file", "policy"],
        "resolved manifest binding",
    )
    binding["artifact"] == basename(artifact_path) ||
        error("resolved manifest binding names the wrong artifact")
    binding["project_file"] == replace(project_relative_path, '\\' => '/') ||
        error("resolved manifest binding names the wrong Project.toml")
    binding["policy"] == MANIFEST_BINDING_POLICY ||
        error("resolved manifest binding has the wrong source-control policy")
    binding["sha256"] isa AbstractString &&
        occursin(r"^[0-9a-f]{64}$", binding["sha256"]) ||
        error("resolved manifest binding has an invalid SHA-256 digest")
    binding["sha256"] == file_sha256(artifact_path) ||
        error("resolved manifest SHA-256 does not match the evidence artifact")

    manifest = TOML.parsefile(artifact_path)
    get(manifest, "manifest_format", nothing) == "2.0" ||
        error("resolved manifest has an unsupported format")
    project_hash = get(manifest, "project_hash", nothing)
    binding["project_hash"] == project_hash ||
        error("resolved manifest project_hash does not match metadata")
    project_hash == current_project_resolve_hash(joinpath(ROOT, project_relative_path)) ||
        error("resolved manifest project_hash does not match the current Project.toml")
    return true
end

